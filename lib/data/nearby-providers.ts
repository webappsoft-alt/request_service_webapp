function defaultStreet(id: string) {
  let hash = 0;
  for (const character of id) hash = (hash * 31 + character.charCodeAt(0)) >>> 0;
  return `${100 + (hash % 8900)} Main Street`;
}

function localProvider(
  provider: Omit<Provider, "workingHours" | "gallery" | "reviews" | "website" | "featured" | "street"> & {
    street?: string;
  },
): Provider {
  return {
    ...provider,
    street: provider.street ?? defaultStreet(provider.id),
    workingHours: weekdayHours,
    gallery: [],
    reviews: [],
    featured: false,
  };
}

